#!/usr/bin/env python3
"""Generate LLM paraphrases of base prompts using multiple model families.

Implements the LLM wave of plan §"Randomisation → Prompt paraphrases".
Each paraphrase slot is generated by a different model family so that
paraphraser-side wording bias does not coincide with the evaluator's
family.

Default slot-to-provider mapping (matches the plan):
    01 = original (project authors; never overwritten)
    02 = OpenAI (GPT-5)
    03 = Google (Gemini 2.5 Pro)
    04 = Anthropic (Claude Sonnet 4.5)

Usage:
    python generate_paraphrases.py
    python generate_paraphrases.py --slots 2 3 4
    python generate_paraphrases.py --scenarios scenario_1a --slots 2
    python generate_paraphrases.py --skip-existing

Each provider's SDK is imported lazily only when that provider is needed.
Required:  ANTHROPIC_API_KEY, OPENAI_API_KEY, GEMINI_API_KEY (the latter two
only if their slots are generated).

Pip:
    pip install anthropic openai google-genai
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Iterable

PARAPHRASE_PROMPT = """You are paraphrasing a task description for a code-writing assistant.

Your job:
- Preserve every factual statement: data file paths and column names; exact numerical parameters; exact distributional assumptions; the framework or language constraint if any; the output file path and its required columns; the structural features mentioned about the data; the expected error-handling behaviour.
- Vary the wording, ordering, headings, sentence structure, and tone.
- Do not add, remove, or reinterpret any factual content.
- Do not add examples, hints, advice, methodological suggestions, or strategies for solving the task.
- Output only the paraphrased task description in markdown. No preamble. No commentary. No explanation of what you changed.

Original task description follows after the dashes.

---
{base_prompt}
---

Paraphrased task description:"""

# (provider, model) per slot
SLOT_DEFAULTS: dict[int, tuple[str, str]] = {
    2: ("openai", "gpt-5"),
    3: ("google", "gemini-2.5-flash"),      # 2.5 Pro has no free tier; Flash does
    4: ("anthropic", "claude-sonnet-4-5"),
}

PARAPHRASE_TEMPERATURE = 0.7
MAX_TOKENS = 4096


# ---------------------------------------------------------------------------
# Provider adapters
# ---------------------------------------------------------------------------

def call_anthropic(model: str, user_prompt: str) -> str:
    try:
        import anthropic
    except ImportError:
        sys.exit("anthropic SDK not installed: pip install anthropic")
    client = anthropic.Anthropic()
    msg = client.messages.create(
        model=model,
        max_tokens=MAX_TOKENS,
        temperature=PARAPHRASE_TEMPERATURE,
        messages=[{"role": "user", "content": user_prompt}],
    )
    return msg.content[0].text.strip()


def call_openai(model: str, user_prompt: str) -> str:
    try:
        import openai
    except ImportError:
        sys.exit("openai SDK not installed: pip install openai")
    client = openai.OpenAI()
    # GPT-5 family uses `max_completion_tokens` and ignores arbitrary
    # `temperature`; passing it triggers a 400. We pass neither and let the
    # model use its defaults (which include reasoning).
    resp = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": user_prompt}],
        max_completion_tokens=MAX_TOKENS,
    )
    return resp.choices[0].message.content.strip()


def call_google(model: str, user_prompt: str) -> str:
    try:
        from google import genai
        from google.genai import types
    except ImportError:
        sys.exit("google-genai SDK not installed: pip install google-genai")
    client = genai.Client()
    resp = client.models.generate_content(
        model=model,
        contents=user_prompt,
        config=types.GenerateContentConfig(
            temperature=PARAPHRASE_TEMPERATURE,
            max_output_tokens=MAX_TOKENS,
        ),
    )
    return resp.text.strip()


def call_xai(model: str, user_prompt: str) -> str:
    """xAI's Grok models via OpenAI-compatible endpoint."""
    try:
        import openai
    except ImportError:
        sys.exit("openai SDK not installed (required for xAI compat): pip install openai")
    api_key = os.environ.get("XAI_API_KEY")
    if not api_key:
        sys.exit("XAI_API_KEY not set")
    client = openai.OpenAI(api_key=api_key, base_url="https://api.x.ai/v1")
    resp = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": user_prompt}],
        temperature=PARAPHRASE_TEMPERATURE,
        max_tokens=MAX_TOKENS,
    )
    return resp.choices[0].message.content.strip()


PROVIDERS = {
    "anthropic": call_anthropic,
    "openai":    call_openai,
    "google":    call_google,
    "xai":       call_xai,
}


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------

def paraphrase_one(provider: str, model: str, base_text: str,
                   *, max_attempts: int = 5, base_delay: float = 5.0) -> str:
    if provider not in PROVIDERS:
        sys.exit(f"Unknown provider: {provider}. Choose from {sorted(PROVIDERS)}")
    user_prompt = PARAPHRASE_PROMPT.format(base_prompt=base_text)
    import time
    last_err = None
    for attempt in range(1, max_attempts + 1):
        try:
            return PROVIDERS[provider](model, user_prompt)
        except Exception as e:
            last_err = e
            msg = str(e)
            transient = any(s in msg for s in ("503", "529", "UNAVAILABLE", "overloaded", "rate", "RATE_LIMIT"))
            if not transient or attempt == max_attempts:
                raise
            delay = base_delay * (2 ** (attempt - 1))
            print(f"  attempt {attempt}/{max_attempts} hit transient error ({type(e).__name__}); "
                  f"retrying in {delay:.0f}s ...", flush=True)
            time.sleep(delay)
    raise last_err  # unreachable


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--prompts-dir", type=Path, default=Path("prompts"))
    p.add_argument("--scenarios", nargs="+", default=["scenario_1a", "scenario_1b", "scenario_2", "scenario_3"])
    p.add_argument("--conditions", nargs="+", default=["no-spec", "julia", "epiaware"])
    p.add_argument("--slots", nargs="+", type=int, default=[2, 3, 4],
                   help="paraphrase slots to fill (defaults: 2=OpenAI, 3=Google, 4=Anthropic)")
    p.add_argument("--skip-existing", action="store_true",
                   help="skip slots whose file already exists (default: overwrite)")
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args()

    if 1 in args.slots:
        sys.exit("Refusing to overwrite slot 01 (the base prompt).")
    bad_slots = [s for s in args.slots if s not in SLOT_DEFAULTS]
    if bad_slots:
        sys.exit(f"No default provider for slots {bad_slots}; recognised slots: {sorted(SLOT_DEFAULTS)}")

    n_done = n_skipped = 0
    n_planned = len(args.scenarios) * len(args.conditions) * len(args.slots)

    for sc in args.scenarios:
        for c in args.conditions:
            base = args.prompts_dir / sc / "paraphrases" / c / "01.md"
            if not base.exists():
                print(f"SKIP missing base: {base}")
                continue
            base_text = base.read_text()
            for slot in args.slots:
                provider, model = SLOT_DEFAULTS[slot]
                out_path = args.prompts_dir / sc / "paraphrases" / c / f"{slot:02d}.md"
                if args.skip_existing and out_path.exists():
                    print(f"SKIP existing: {out_path}")
                    n_skipped += 1
                    continue
                if args.dry_run:
                    print(f"would write {out_path}  via  {provider}/{model}")
                    continue
                print(f"generating {sc}/{c}/{slot:02d}.md via {provider}/{model} ...", flush=True)
                para = paraphrase_one(provider, model, base_text)
                out_path.parent.mkdir(parents=True, exist_ok=True)
                out_path.write_text(para)
                print(f"  wrote {len(para)} chars")
                n_done += 1

    print(f"\nplanned={n_planned}  written={n_done}  skipped={n_skipped}")


if __name__ == "__main__":
    main()
